#!/usr/bin/env node
// Embeds data/*.json into js/data.js so the site works from file:// (browsers block fetch() of local files).
// data/*.json stays the source of truth; test/run.js fails if js/data.js is stale.
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
function render() {
  const p = fs.readFileSync(path.join(ROOT, "data/presets.json"), "utf8");
  const c = fs.readFileSync(path.join(ROOT, "data/contracts.json"), "utf8");
  return "/* GENERATED by tools/build-data.js from data/*.json. Do not edit. */\n" +
    "window.PDC_DATA = {presets: " + JSON.stringify(JSON.parse(p)) + ",\ncontracts: " + JSON.stringify(JSON.parse(c)) + "};\n";
}
module.exports = { render };
if (require.main === module) { fs.writeFileSync(path.join(ROOT, "js/data.js"), render()); console.log("wrote js/data.js"); }
